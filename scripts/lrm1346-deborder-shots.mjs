#!/usr/bin/env node
/**
 * LRM-1346 gate shots — message shell / group edge, BEFORE (`origin/dev`) vs
 * AFTER (working tree), at 1440 / 700 / 360 × 分组首/中/末/独立.
 *
 * The harness renders class strings, not prose: this script reads them out of
 * `channel-message-bubble.tsx` at both revisions, safelists exactly those
 * utilities for Tailwind, then measures `border*Width` per row in real Chromium.
 * If the component stops shipping what the harness photographs, extraction
 * fails loudly instead of producing a pretty lie.
 *
 * Usage: node scripts/lrm1346-deborder-shots.mjs
 * Temporary tooling: delete once the frames are attached to LRM-1346.
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const COMPONENT = "packages/views/channels/components/channel-message-bubble.tsx";
const harnessDir = resolve(root, "scripts/lrm1346-harness");
const outDir = resolve(root, "e2e/artifacts/lrm1346");
mkdirSync(outDir, { recursive: true });

const readRev = (rev) =>
  rev === "WORKTREE"
    ? readFileSync(resolve(root, COMPONENT), "utf8")
    : execFileSync("git", ["show", `${rev}:${COMPONENT}`], { cwd: root, encoding: "utf8" });

const fail = (msg) => {
  console.error(`lrm1346-shots: ${msg}`);
  process.exit(1);
};

/** `const MESSAGE_SHELL_CLASS = "…"` — possibly wrapped onto the next line. */
function shellClass(src, label) {
  const m = src.match(/const MESSAGE_SHELL_CLASS =\s*\n?\s*"([^"]+)"/);
  if (!m) fail(`${label}: cannot read MESSAGE_SHELL_CLASS from ${COMPONENT}`);
  return m[1];
}

/**
 * Group segments. BEFORE ships `messageShellEdgeClass()`; AFTER deleted it, and
 * "deleted" is part of the claim — so an AFTER source that still has the helper
 * is an extraction failure, not an empty edge set.
 */
function edgeClasses(src, label, { expectHelper }) {
  const fn = src.match(/function messageShellEdgeClass\([^)]*\)\s*\{([\s\S]*?)\n\}/);
  if (expectHelper) {
    if (!fn) fail(`${label}: expected messageShellEdgeClass() but it is gone`);
    const branch = (re) => {
      const m = fn[1].match(re);
      if (!m) fail(`${label}: cannot read the ${re} branch of messageShellEdgeClass()`);
      return m[1];
    };
    return {
      solo: branch(/groupStart && groupEnd\) return "([^"]+)"/),
      head: branch(/if \(groupStart\) return "([^"]+)"/),
      tail: branch(/if \(groupEnd\) return "([^"]+)"/),
      middle: branch(/\n\s*return "([^"]+)";/),
    };
  }
  if (fn) fail(`${label}: messageShellEdgeClass() is still present — the group edges did not go`);
  if (/messageShellEdgeClass\(/.test(src)) fail(`${label}: messageShellEdgeClass is still called`);
  return { solo: "", head: "", middle: "", tail: "" };
}

function authorRowReserve(src, label) {
  const mq = src.match(/const FINE_DESKTOP_MQ = "([^"]+)"/);
  const pr = src.match(/\$\{FINE_DESKTOP_MQ\}:(pr-\[\d+px\])/);
  if (!mq || !pr) fail(`${label}: cannot read the LRM-1331 author-row reserve`);
  return `${mq[1]}:${pr[1]}`;
}

/**
 * BEFORE defaults to `origin/dev`, but once the knife is merged `dev` *is* the
 * AFTER state — pass the merge commit's first parent instead, e.g.
 * `LRM1346_BEFORE_REV=74084953f^1`.
 */
const BEFORE_REV = process.env.LRM1346_BEFORE_REV ?? "origin/dev";

const beforeSrc = readRev(BEFORE_REV);
const afterSrc = readRev("WORKTREE");

const classes = {
  before: {
    shell: shellClass(beforeSrc, "BEFORE"),
    edge: edgeClasses(beforeSrc, "BEFORE", { expectHelper: true }),
  },
  after: {
    shell: shellClass(afterSrc, "AFTER"),
    edge: edgeClasses(afterSrc, "AFTER", { expectHelper: false }),
  },
  authorRowReserve: authorRowReserve(afterSrc, "AFTER"),
};

// The ① lock, stated as a check rather than a hope.
const afterTokens = [
  classes.after.shell,
  ...Object.values(classes.after.edge),
].join(" ");
if (/(^|[\s:])border|rounded-[tb]?-?lg|\bring-1\b|\bshadow-/.test(afterTokens)) {
  fail(`AFTER still ships an edge utility: "${afterTokens.trim()}"`);
}

writeFileSync(
  resolve(harnessDir, "classes.generated.json"),
  `${JSON.stringify(classes, null, 2)}\n`,
);

const safelist = new Set(
  [
    classes.before.shell,
    ...Object.values(classes.before.edge),
    classes.after.shell,
    ...Object.values(classes.after.edge),
    classes.authorRowReserve,
  ]
    .join(" ")
    .split(/\s+/)
    .filter(Boolean),
);
writeFileSync(
  resolve(harnessDir, "safelist.generated.css"),
  `/* generated by scripts/lrm1346-deborder-shots.mjs — do not edit */\n${[...safelist]
    .map((token) => `@source inline("${token}");`)
    .join("\n")}\n`,
);

const base = process.env.HARNESS_URL ?? "http://127.0.0.1:5346/";
const viewports = { 1440: 980, 700: 980, 360: 780 };
const ROW_IDS = ["head", "middle", "tail", "solo"];

const browser = await chromium.launch();
const report = { component: COMPONENT, beforeRev: execFileSync("git", ["rev-parse", "--short", BEFORE_REV], { cwd: root, encoding: "utf8" }).trim(), afterRev: execFileSync("git", ["rev-parse", "--short", "HEAD"], { cwd: root, encoding: "utf8" }).trim(), classes, cells: {} };

for (const variant of ["before", "after"]) {
  for (const [width, height] of Object.entries(viewports)) {
    const page = await browser.newPage({
      viewport: { width: Number(width), height },
      locale: "zh-CN",
    });
    page.setDefaultTimeout(60_000);
    await page.goto(`${base}?variant=${variant}`, { waitUntil: "networkidle" });
    await page.locator('[data-testid="message-shell"]').first().waitFor();
    await page.waitForTimeout(200);
    const file = `lrm1346-${variant}-${width}.png`;
    await page.screenshot({ path: resolve(outDir, file), fullPage: false });
    report.cells[`${variant}@${width}`] = {
      file,
      rows: await page.evaluate((ids) => {
        const out = {};
        for (const id of ids) {
          const el = document.querySelector(`[data-shell="${id}"]`);
          const s = getComputedStyle(el);
          out[id] = {
            border: [s.borderTopWidth, s.borderRightWidth, s.borderBottomWidth, s.borderLeftWidth]
              .map((v) => Number.parseFloat(v))
              .join("/"),
            radius: [s.borderTopLeftRadius, s.borderBottomLeftRadius].join("/"),
            width: Math.round(el.getBoundingClientRect().width),
          };
        }
        return out;
      }, ROW_IDS),
    };
    await page.close();
  }
}
await browser.close();

writeFileSync(resolve(outDir, "report.json"), `${JSON.stringify(report, null, 2)}\n`);
console.log(JSON.stringify(report, null, 2));
